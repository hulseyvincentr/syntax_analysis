def validate_args(args: argparse.Namespace) -> None:
    if not 0 < args.top_fraction <= 1:
        raise ValueError("--top-fraction must be in (0, 1].")
    if args.balance_draws < 1:
        raise ValueError("--balance-draws must be at least 1.")
    if args.smooth_window_days < 1:
        raise ValueError("--smooth-window-days must be at least 1.")
    if args.x_min >= args.x_max:
        raise ValueError("--x-min must be less than --x-max.")
    for path in [args.scatter_csv, args.duration_long_csv]:
        if not path.exists():
            raise FileNotFoundError(path)
    if args.metadata_excel is not None and not args.metadata_excel.exists():
        raise FileNotFoundError(args.metadata_excel)


def main() -> None:
    args = build_parser().parse_args()
    validate_args(args)
    show = bool(args.show and not args.no_show)
    out_dir = ensure_dir(args.out_dir)
    colors = load_colors(args.color_json)

    hit_map, treatment_dates = load_metadata(
        args.metadata_excel,
        preferred_sheet=args.metadata_sheet,
        animal_col_requested=args.metadata_animal_col,
        hit_col_requested=args.metadata_hit_col,
        date_col_requested=args.metadata_date_col,
    )
    if not hit_map:
        print("[INFO] No metadata workbook supplied; lesion groups will be read from the generated CSV columns.")

    selected, audit = prepare_selected_scatter(
        args.scatter_csv,
        hit_map=hit_map,
        top_fraction=args.top_fraction,
        rank_on=args.rank_on,
        pre_group=args.pre_group,
        post_group=args.post_group,
        min_n_phrases=args.min_scatter_phrases,
        animal_col_requested=args.scatter_animal_col,
        syllable_col_requested=args.scatter_syllable_col,
        group_col_requested=args.scatter_group_col,
        variance_col_requested=args.scatter_variance_col,
        n_col_requested=args.scatter_n_col,
    )
    if selected.empty:
        raise ValueError("No eligible bird × syllable pairs were selected from the scatter CSV.")
    if selected["display_group"].eq(UNKNOWN_GROUP).all():
        raise ValueError(
            "No lesion-group labels were found. Supply --metadata-excel or ensure the generated CSVs "
            "contain a lesion_group column."
        )
    selected.to_csv(out_dir / "top15_selected_syllables_and_scatter_metrics.csv", index=False)
    audit.to_csv(out_dir / "top15_selection_audit_by_bird.csv", index=False)
    selected[["animal_id", "syllable"]].to_csv(out_dir / "top15_selected_animal_syllable_pairs.csv", index=False)

    plot_sd_scatter(
        selected,
        out_dir / "Figure3_top15_SD_scatter.png",
        colors=colors,
        dpi=args.dpi,
        show=show,
    )
    save_scatter_legend(out_dir / "Figure3_top15_lesion_group_legend.png", colors, args.dpi)

    long_df = prepare_long_table(
        args.duration_long_csv,
        hit_map=hit_map,
        treatment_dates=treatment_dates,
        duration_unit=args.duration_unit,
        animal_col_requested=args.long_animal_col,
        syllable_col_requested=args.long_syllable_col,
        duration_col_requested=args.long_duration_col,
        day_col_requested=args.long_day_col,
        date_col_requested=args.long_date_col,
        period_col_requested=args.long_period_col,
    )
    long_df = assign_analysis_periods(
        long_df,
        pre_group=args.pre_group,
        post_group=args.post_group,
        pre_start_day=args.pre_start_day,
        pre_end_day=args.pre_end_day,
        post_start_day=args.post_start_day,
        post_end_day=args.post_end_day,
    )

    syllable_metrics = calculate_selected_cv_metrics(
        long_df,
        selected,
        min_period_phrases=args.min_period_phrases,
        min_period_days=args.min_period_days,
        balance_draws=args.balance_draws,
        seed=args.seed,
    )
    if syllable_metrics.empty:
        raise ValueError(
            "No selected syllables had enough late-pre and post phrase occurrences for balanced CV metrics."
        )
    syllable_metrics.to_csv(out_dir / "top15_animal_syllable_balanced_CV_metrics.csv", index=False)

    bird_metrics = bird_level_cv_table(syllable_metrics)
    bird_metrics.to_csv(out_dir / "top15_bird_level_delta_CV.csv", index=False)
    tests = run_pairwise_tests(
        bird_metrics,
        seed=args.seed,
        bootstrap_reps=args.bootstrap_reps,
        max_exact=args.max_exact_permutations,
        monte_carlo_reps=args.monte_carlo_permutations,
    )
    tests.to_csv(out_dir / "top15_pairwise_exact_permutation_tests.csv", index=False)
    plot_delta_cv_boxplot(
        bird_metrics,
        tests,
        out_dir / "Figure3_top15_delta_CV_boxplot.png",
        colors=colors,
        annotation_style=args.annotation_style,
        dpi=args.dpi,
        show=show,
    )

    daily_syllable, bird_daily = calculate_daily_cv(
        long_df,
        selected,
        min_daily_phrases=args.min_daily_phrases,
        x_min=args.x_min,
        x_max=args.x_max,
    )
    daily_syllable.to_csv(out_dir / "top15_daily_CV_by_bird_syllable.csv", index=False)
    bird_daily.to_csv(out_dir / "top15_daily_CV_by_bird.csv", index=False)
    normalized, baseline = normalize_to_late_pre(
        bird_daily,
        baseline_start=args.pre_start_day,
        baseline_end=args.pre_end_day,
        min_baseline_days=args.min_baseline_days,
    )
    normalized.to_csv(out_dir / "top15_daily_CV_by_bird_normalized.csv", index=False)
    baseline.to_csv(out_dir / "top15_CV_baseline_summary_by_bird.csv", index=False)
    bird_rolling, rolling_summary = rolling_equal_bird_summary(
        normalized,
        x_min=args.x_min,
        x_max=args.x_max,
        window_days=args.smooth_window_days,
        min_observations_per_bird_window=args.min_observations_per_bird_window,
        min_birds=args.min_birds_for_summary,
    )
    bird_rolling.to_csv(out_dir / "top15_CV_equal_bird_rolling_values.csv", index=False)
    rolling_summary.to_csv(out_dir / "top15_CV_equal_bird_rolling_summary.csv", index=False)
    plot_cv_timecourse(
        rolling_summary,
        out_dir / "Figure3_top15_CV_rolling_timecourse.png",
        colors=colors,
        x_min=args.x_min,
        x_max=args.x_max,
        y_min=args.timecourse_y_min,
        y_max=args.timecourse_y_max,
        dpi=args.dpi,
        show=show,
    )

    summary_path = out_dir / "top15_figure3_analysis_summary.txt"
    write_summary(
        summary_path,
        selected=selected,
        audit=audit,
        syllable_metrics=syllable_metrics,
        bird_metrics=bird_metrics,
        tests=tests,
        args=args,
    )

    print("[OK] PNG panels written:")
    for name in [
        "Figure3_top15_SD_scatter.png",
        "Figure3_top15_delta_CV_boxplot.png",
        "Figure3_top15_CV_rolling_timecourse.png",
        "Figure3_top15_lesion_group_legend.png",
    ]:
        print(f"  {out_dir / name}")
    print(f"[OK] Tables and summary written to: {out_dir}")


if __name__ == "__main__":
    main()
