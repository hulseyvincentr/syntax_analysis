def normalize_hit_type(value: Any) -> str:
    text = normalized_text(value)
    compact = text.replace(" ", "")
    if not text:
        return UNKNOWN_GROUP
    if "sham" in text or ("saline" in text and "lesion" not in text):
        return SHAM_GROUP
    if "single hit" in text or "lateral only" in text or "lateral hit only" in text:
        return LATERAL_GROUP
    if "area x not visible" in text or "large lesion" in text or "largelesion" in compact:
        return COMPLETE_ML_GROUP
    if "complete" in text and "medial" in text and "lateral" in text:
        return COMPLETE_ML_GROUP
    if ("medial" in text and "lateral" in text) or "m+l" in compact or "combined" in text:
        return PARTIAL_ML_GROUP
    if compact in {"ml", "mediallateral", "medial+lateral", "medialandlateral"}:
        return PARTIAL_ML_GROUP
    return standardize_text(value) or UNKNOWN_GROUP


def pooled_group(value: Any) -> str:
    group = normalize_hit_type(value)
    if group in {COMPLETE_ML_GROUP, PARTIAL_ML_GROUP, POOLED_ML_GROUP}:
        return POOLED_ML_GROUP
    return group


def load_colors(path: Optional[Path]) -> dict[str, str]:
    colors = dict(DEFAULT_COLORS)
    if path is None:
        return colors
    with path.open("r", encoding="utf-8") as handle:
        cfg = json.load(handle)

    # Supports both the original Figure 3 {groups:{...}} format and the simpler
    # Figure 4 {colors:{...}} files supplied with this analysis.
    if isinstance(cfg.get("groups"), dict):
        for group, info in cfg["groups"].items():
            if isinstance(info, dict) and info.get("color"):
                canonical = normalize_hit_type(group)
                colors[canonical] = str(info["color"])
    if isinstance(cfg.get("colors"), dict):
        for group, color in cfg["colors"].items():
            canonical = normalize_hit_type(group)
            if canonical == PARTIAL_ML_GROUP and "medial" in normalized_text(group):
                colors[PARTIAL_ML_GROUP] = str(color)
                colors[POOLED_ML_GROUP] = str(color)
            else:
                colors[canonical] = str(color)
    return colors


