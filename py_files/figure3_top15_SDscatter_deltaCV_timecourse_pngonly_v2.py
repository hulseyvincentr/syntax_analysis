def calculate_daily_cv(
    long_df: pd.DataFrame,
    selected_pairs: pd.DataFrame,
    *,
    min_daily_phrases: int,
    x_min: int,
    x_max: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    selected = selected_pairs[["animal_id", "syllable"]].drop_duplicates().copy()
    selected["animal_id"] = selected["animal_id"].astype(str)
    selected["syllable"] = selected["syllable"].astype(str)
    work = long_df.merge(selected, on=["animal_id", "syllable"], how="inner")
    work["relative_day"] = pd.to_numeric(work["relative_day"], errors="coerce")
    work = work[np.isfinite(work["relative_day"])]
    work = work[work["relative_day"].between(x_min, x_max)].copy()
    if work.empty:
        raise ValueError(
            "No selected phrase occurrences had a usable relative day. Provide a relative-day "
            "column, or a recording date plus treatment dates in the metadata workbook."
        )

    per_syllable = (
        work.groupby(["animal_id", "syllable", "display_group", "relative_day"], dropna=False)["duration_s"]
        .agg(n_phrases="size", mean_s="mean", sd_s="std")
        .reset_index()
    )
    per_syllable = per_syllable[per_syllable["n_phrases"] >= min_daily_phrases].copy()
    per_syllable["cv"] = per_syllable["sd_s"] / per_syllable["mean_s"]
    per_syllable.loc[~np.isfinite(per_syllable["cv"]) | (per_syllable["mean_s"] <= 0), "cv"] = np.nan
    per_syllable["pooled_group"] = per_syllable["display_group"].map(pooled_group)

    bird_daily = (
        per_syllable.groupby(["animal_id", "pooled_group", "relative_day"], dropna=False)
        .agg(
            cv=("cv", "median"),
            n_selected_syllables=("syllable", "nunique"),
            total_phrases=("n_phrases", "sum"),
        )
        .reset_index()
    )
    return per_syllable, bird_daily


def normalize_to_late_pre(
    bird_daily: pd.DataFrame,
    *,
    baseline_start: int,
    baseline_end: int,
    min_baseline_days: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    baseline_rows = []
    for bird, group in bird_daily.groupby("animal_id", sort=True):
        baseline = group[group["relative_day"].between(baseline_start, baseline_end)]["cv"].dropna().to_numpy()
        if len(baseline) < min_baseline_days:
            warnings.warn(
                f"Skipping {bird} from the normalized time course: {len(baseline)} usable baseline days; "
                f"need {min_baseline_days}."
            )
            continue
        baseline_rows.append(
            {
                "animal_id": bird,
                "baseline_start_day": baseline_start,
                "baseline_end_day": baseline_end,
                "n_baseline_days": len(baseline),
                "baseline_cv_median": float(np.median(baseline)),
                "baseline_cv_q25": float(np.percentile(baseline, 25)),
                "baseline_cv_q75": float(np.percentile(baseline, 75)),
            }
        )
    baseline_df = pd.DataFrame(baseline_rows)
    if baseline_df.empty:
        raise ValueError("No birds had enough late-pre baseline days for the CV time course.")
    normalized = bird_daily.merge(baseline_df, on="animal_id", how="inner")
    valid = normalized["baseline_cv_median"] > 0
    normalized = normalized[valid].copy()
    normalized["cv_fold_change"] = normalized["cv"] / normalized["baseline_cv_median"]
    return normalized, baseline_df


def rolling_equal_bird_summary(
    normalized: pd.DataFrame,
    *,
    x_min: int,
    x_max: int,
    window_days: int,
    min_observations_per_bird_window: int,
    min_birds: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    half = window_days // 2
    bird_rows: list[dict[str, Any]] = []
    for group_name in TIMECOURSE_ORDER:
        group_df = normalized[normalized["pooled_group"] == group_name]
        for day in range(x_min, x_max + 1):
            for bird, bird_df in group_df.groupby("animal_id", sort=True):
                window = bird_df[bird_df["relative_day"].between(day - half, day + half)]
                if day < 0:
                    window = window[window["relative_day"] < 0]
                elif day > 0:
                    window = window[window["relative_day"] > 0]
                else:
                    window = window[window["relative_day"] == 0]
                values = window["cv_fold_change"].dropna().to_numpy(dtype=float)
                if len(values) < min_observations_per_bird_window:
                    continue
                bird_rows.append(
                    {
                        "pooled_group": group_name,
                        "animal_id": bird,
                        "relative_day": day,
                        "rolling_cv_fold_change": float(np.median(values)),
                        "n_observations_in_window": len(values),
                    }
                )
    bird_rolling = pd.DataFrame(bird_rows)
    if bird_rolling.empty:
        return bird_rolling, pd.DataFrame()

    summary_rows = []
    for (group_name, day), group in bird_rolling.groupby(["pooled_group", "relative_day"], sort=True):
        values = group["rolling_cv_fold_change"].dropna().to_numpy(dtype=float)
        if len(values) < min_birds:
            continue
        summary_rows.append(
            {
                "pooled_group": group_name,
                "relative_day": day,
                "n_birds": len(values),
                "median": float(np.median(values)),
                "q25": float(np.percentile(values, 25)),
                "q75": float(np.percentile(values, 75)),
            }
        )
    return bird_rolling, pd.DataFrame(summary_rows)


