def standardize_text(value: Any) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    return " ".join(str(value).strip().split())


def normalized_text(value: Any) -> str:
    return standardize_text(value).lower().replace("_", " ").replace("-", " ")


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def stable_rng(seed: int, *parts: object) -> np.random.Generator:
    payload = "|".join([str(seed), *(str(part) for part in parts)]).encode("utf-8")
    digest = hashlib.sha256(payload).digest()
    derived = int.from_bytes(digest[:8], "little", signed=False)
    return np.random.default_rng(derived)


def first_existing_column(
    df: pd.DataFrame,
    requested: Optional[str],
    candidates: Sequence[str],
    label: str,
    *,
    required: bool = True,
) -> Optional[str]:
    if requested:
        if requested in df.columns:
            return requested
        raise ValueError(
            f"Requested {label} column {requested!r} was not found. "
            f"Available columns: {list(df.columns)}"
        )

    lookup = {
        "".join(ch.lower() for ch in str(col) if ch.isalnum()): col
        for col in df.columns
    }
    for candidate in candidates:
        key = "".join(ch.lower() for ch in candidate if ch.isalnum())
        if key in lookup:
            return lookup[key]
    if required:
        raise ValueError(
            f"Could not identify the {label} column. Available columns: {list(df.columns)}"
        )
    return None


def plain_number(x: float, pos: object = None) -> str:
    try:
        value = float(x)
    except Exception:
        return ""
    if not np.isfinite(value):
        return ""
    if abs(value) < 1e-12:
        return "0"
    magnitude = abs(value)
    if magnitude >= 10:
        text = f"{value:.0f}"
    elif magnitude >= 1:
        text = f"{value:.1f}"
    else:
        text = f"{value:.2f}"
    return text.rstrip("0").rstrip(".")


def pretty_axes(ax: plt.Axes, tick_size: float = 13.5) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_linewidth(1.0)
    ax.spines["bottom"].set_linewidth(1.0)
    ax.tick_params(axis="both", labelsize=tick_size, width=1.0, length=4)


def save_png(fig: plt.Figure, path: Path, dpi: int, show: bool) -> Path:
    if path.suffix.lower() != ".png":
        path = path.with_suffix(".png")
    fig.savefig(path, dpi=dpi, bbox_inches="tight", pad_inches=0.08)
    if show:
        plt.show()
    else:
        plt.close(fig)
    return path


def format_p(p: float) -> str:
    if not np.isfinite(p):
        return "NA"
    if p < 0.001:
        return "<0.001"
    return f"{p:.3f}"


def p_to_stars(p: float) -> str:
    if not np.isfinite(p):
        return "NA"
    if p < 0.001:
        return "***"
    if p < 0.01:
        return "**"
    if p < 0.05:
        return "*"
    return "n.s."


def sample_sd(values: np.ndarray) -> float:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    return float(np.std(values, ddof=1)) if values.size >= 2 else np.nan


def safe_mean(values: Sequence[float]) -> float:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    return float(np.mean(arr)) if arr.size else np.nan


def safe_median(values: Sequence[float]) -> float:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    return float(np.median(arr)) if arr.size else np.nan


