"""Create the top-15% Figure 3 phrase-duration panels as PNG files only.

This script makes three manuscript-style panels using one exact within-bird
upper-fraction selection:

1. Late-pre versus post phrase-duration SD scatterplot.
2. Bird-level change-in-CV boxplot.
3. Equal-bird, baseline-normalized CV rolling-median time course.

Selection
---------
Eligible syllables are ranked separately within each bird by the mean of their
late-pre and post phrase-duration variances (``--rank-on pooled`` by default).
The script retains exactly::

    ceil(top_fraction * number_of_eligible_syllables)

syllables per bird. The default ``--top-fraction 0.15`` therefore implements
the upper-15% operating point used in the exploratory analysis. Stable sorting
by syllable label resolves exact rank ties reproducibly.

Statistical unit
----------------
CV is estimated for each selected bird x syllable after equalizing late-pre and
post phrase counts. The script repeats this balancing 200 times by default and
averages the resulting metrics, matching the cutoff-scan analysis. Each bird is
then represented by the median delta-CV across its selected syllables. Exact
bird-label permutation tests compare pooled medial+lateral lesions with
lateral-only and sham groups. Holm correction is applied across the three
pairwise comparisons.

Expected inputs
---------------
--scatter-csv
    The balanced period-level table used for the existing Figure 3 scatter,
    usually ``usage_balanced_phrase_duration_stats.csv``. Required columns are
    detected from common names, including Animal ID, Syllable, Group,
    N_phrases, and Variance_ms2.

--duration-long-csv
    One row per phrase occurrence, with bird, syllable, duration, and either a
    relative-day column or recording date. A Late Pre/Post group column is
    optional because periods can be assigned from relative-day windows.

--metadata-excel
    Optional workbook containing bird IDs and lesion hit types. It is not needed
    when using the CSVs generated by generate_figure3_top15_inputs_from_json.py,
    because those files already contain lesion_group, lesion_surgery_date, and
    relative_day columns.

Example
-------
python figure3_top15_SDscatter_deltaCV_timecourse_pngonly.py \
  --scatter-csv "/Volumes/my_own_SSD/updated_AreaX_outputs/usage_balanced_phrase_duration_stats.csv" \
  --duration-long-csv "/Volumes/my_own_SSD/updated_AreaX_outputs/phrase_duration_batch_outputs/_batch_summary/all_birds_phrase_duration_long_latepre_post_epochs.csv" \
  --out-dir "/Volumes/my_own_SSD/updated_AreaX_outputs/Figure3_top15_CV" \
  --top-fraction 0.15 \
  --rank-on pooled \
  --pre-start-day -14 --pre-end-day -1 \
  --post-start-day 1 --post-end-day 14 \
  --x-min -30 --x-max 30 \
  --no-show

Outputs are PNG and CSV/TXT only; no PDF files are written.
"""

