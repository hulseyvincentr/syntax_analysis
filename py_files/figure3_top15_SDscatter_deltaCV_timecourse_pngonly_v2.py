# -----------------------------------------------------------------------------
# Exact bird-label permutation tests
# -----------------------------------------------------------------------------
def exact_permutation_p(
    x: np.ndarray,
    y: np.ndarray,
    *,
    alternative: str,
    max_exact: int,
    monte_carlo_reps: int,
    rng: np.random.Generator,
) -> tuple[float, str, int]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    x = x[np.isfinite(x)]
    y = y[np.isfinite(y)]
    if len(x) == 0 or len(y) == 0:
        return np.nan, "none", 0
    observed = float(np.mean(x) - np.mean(y))
    pooled = np.concatenate([x, y])
    nx = len(x)
    total = math.comb(len(pooled), nx)

    def extreme(stat: float) -> bool:
        if alternative == "greater":
            return stat >= observed - 1e-15
        if alternative == "less":
            return stat <= observed + 1e-15
        return abs(stat) >= abs(observed) - 1e-15

    if total <= max_exact:
        count = 0
        for indices in itertools.combinations(range(len(pooled)), nx):
            mask = np.zeros(len(pooled), dtype=bool)
            mask[list(indices)] = True
            stat = float(np.mean(pooled[mask]) - np.mean(pooled[~mask]))
            count += int(extreme(stat))
        return count / total, "exact", total

    count = 0
    for _ in range(monte_carlo_reps):
        perm = rng.permutation(pooled)
        stat = float(np.mean(perm[:nx]) - np.mean(perm[nx:]))
        count += int(extreme(stat))
    return (count + 1) / (monte_carlo_reps + 1), "monte_carlo", monte_carlo_reps


def bootstrap_mean_difference_ci(
    x: np.ndarray,
    y: np.ndarray,
    *,
    reps: int,
    rng: np.random.Generator,
) -> tuple[float, float]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    x = x[np.isfinite(x)]
    y = y[np.isfinite(y)]
    if not len(x) or not len(y) or reps < 1:
        return np.nan, np.nan
    boot = np.empty(reps, dtype=float)
    for index in range(reps):
        xb = rng.choice(x, size=len(x), replace=True)
        yb = rng.choice(y, size=len(y), replace=True)
        boot[index] = np.mean(xb) - np.mean(yb)
    low, high = np.percentile(boot, [2.5, 97.5])
    return float(low), float(high)


def holm_adjust(p_values: Sequence[float]) -> np.ndarray:
    p = np.asarray(p_values, dtype=float)
    adjusted = np.full_like(p, np.nan)
    finite_idx = np.where(np.isfinite(p))[0]
    if not len(finite_idx):
        return adjusted
    order = finite_idx[np.argsort(p[finite_idx])]
    running = 0.0
    m = len(order)
    for rank, idx in enumerate(order):
        value = min(1.0, (m - rank) * p[idx])
        running = max(running, value)
        adjusted[idx] = running
    return adjusted


def run_pairwise_tests(
    bird_df: pd.DataFrame,
    *,
    seed: int,
    bootstrap_reps: int,
    max_exact: int,
    monte_carlo_reps: int,
) -> pd.DataFrame:
    comparisons = [
        (POOLED_ML_GROUP, LATERAL_GROUP),
        (POOLED_ML_GROUP, SHAM_GROUP),
        (LATERAL_GROUP, SHAM_GROUP),
    ]
    rows: list[dict[str, Any]] = []
    for group1, group2 in comparisons:
        x = bird_df.loc[bird_df["pooled_group"] == group1, "delta_cv"].to_numpy(dtype=float)
        y = bird_df.loc[bird_df["pooled_group"] == group2, "delta_cv"].to_numpy(dtype=float)
        p_greater, method, n_perm = exact_permutation_p(
            x, y, alternative="greater", max_exact=max_exact,
            monte_carlo_reps=monte_carlo_reps,
            rng=stable_rng(seed, "perm", group1, group2),
        )
        p_two, _, _ = exact_permutation_p(
            x, y, alternative="two-sided", max_exact=max_exact,
            monte_carlo_reps=monte_carlo_reps,
            rng=stable_rng(seed, "perm_two", group1, group2),
        )
        ci_low, ci_high = bootstrap_mean_difference_ci(
            x, y, reps=bootstrap_reps,
            rng=stable_rng(seed, "bootstrap", group1, group2),
        )
        rows.append(
            {
                "comparison": f"{group1}_vs_{group2}",
                "group1": group1,
                "group2": group2,
                "n_group1": len(x),
                "n_group2": len(y),
                "group1_mean_delta_cv": safe_mean(x),
                "group1_median_delta_cv": safe_median(x),
                "group2_mean_delta_cv": safe_mean(y),
                "group2_median_delta_cv": safe_median(y),
                "mean_difference_group1_minus_group2": safe_mean(x) - safe_mean(y),
                "bootstrap_ci_low": ci_low,
                "bootstrap_ci_high": ci_high,
                "alternative": "group1 > group2",
                "p_one_sided": p_greater,
                "p_two_sided": p_two,
                "permutation_method": method,
                "n_permutations": n_perm,
            }
        )
    result = pd.DataFrame(rows)
    if not result.empty:
        result["p_one_sided_holm"] = holm_adjust(result["p_one_sided"].to_numpy())
        result["p_two_sided_holm"] = holm_adjust(result["p_two_sided"].to_numpy())
    return result


